import "server-only";
import { createHmac, timingSafeEqual } from "node:crypto";

// ---------------------------------------------------------------------------------------------
// RFC 6238 TOTP core for the platform (SHA-1, 6 digits, 30-second steps — the same parameters as
// the shared customer helper, src/lib/security/totp.ts, and its provisioning URI).
//
// Why a platform copy: the shared verifyTotp() returns only a boolean against Date.now(), so it
// cannot report WHICH time step matched. Replay prevention needs that step, and PO-01A must not
// modify customer MFA code. Secrets are still generated by the shared generateTotpSecret();
// verify-platform-auth cross-checks this implementation against the shared verifier.
// ---------------------------------------------------------------------------------------------

export const TOTP_STEP_SECONDS = 30;
const DIGITS = 6;
const BASE32 = "ABCDEFGHIJKLMNOPQRSTUVWXYZ234567";

/** Strict base32 decode: unlike the shared helper, invalid characters are an error, not skipped. */
function base32Decode(input: string): Buffer {
  const clean = input.replace(/=+$/, "");
  if (!/^[A-Z2-7]+$/.test(clean)) throw new Error("invalid base32 TOTP secret");
  let bits = 0;
  let value = 0;
  const out: number[] = [];
  for (const char of clean) {
    value = (value << 5) | BASE32.indexOf(char);
    bits += 5;
    if (bits >= 8) {
      out.push((value >>> (bits - 8)) & 0xff);
      bits -= 8;
    }
  }
  return Buffer.from(out);
}

export function totpStepAt(at: Date): number {
  return Math.floor(at.getTime() / 1000 / TOTP_STEP_SECONDS);
}

export function hotpCode(secret: string, counter: number): string {
  const key = base32Decode(secret);
  const msg = Buffer.alloc(8);
  msg.writeBigUInt64BE(BigInt(counter));
  const mac = createHmac("sha1", key).update(msg).digest();
  const offset = mac[mac.length - 1] & 0x0f;
  const binary = ((mac[offset] & 0x7f) << 24) | ((mac[offset + 1] & 0xff) << 16) | ((mac[offset + 2] & 0xff) << 8) | (mac[offset + 3] & 0xff);
  return (binary % 10 ** DIGITS).toString().padStart(DIGITS, "0");
}

/**
 * The time step a code belongs to (±window steps of clock drift), or null. Every candidate is
 * compared in constant time with no early exit; if several steps produce the same digits the
 * LATEST step is returned, which is the conservative choice for replay tracking.
 */
export function matchTotpStep(secret: string, code: string, at: Date, window = 1): number | null {
  const clean = String(code ?? "").replace(/\s/g, "");
  if (!/^\d{6}$/.test(clean)) return null;
  const given = Buffer.from(clean);
  const current = totpStepAt(at);
  let matched: number | null = null;
  for (let i = -window; i <= window; i++) {
    const expected = Buffer.from(hotpCode(secret, current + i));
    if (timingSafeEqual(expected, given)) matched = current + i;
  }
  return matched;
}
