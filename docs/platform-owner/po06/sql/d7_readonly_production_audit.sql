FROM orgs g LEFT JOIN tenant_primary_owners p ON p.org_id = g.id;
\else
\echo '(tenant_primary_owners is not installed: no company has a primary owner mapping yet — every company counts)'
SELECT count(*) AS companies, count(*) AS without_primary_owner FROM orgs;
\endif

\echo '=== D7-06 subscription states'
\if :has_subs
SELECT lifecycle_state, cycle, (superseded_at IS NULL) AS current, count(*) AS subscriptions,
       count(*) FILTER (WHERE superseded_at IS NULL AND end_date < current_date) AS current_past_end_date
