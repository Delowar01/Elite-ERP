\echo '=== D7-11 objects or conditions that could prevent the migration'
SELECT (SELECT count(*) FROM pg_namespace WHERE nspname IN ('po02a_reference', 'po02d1_reference', 'po03c_reference')) AS leftover_scratch_schemas,
       (SELECT count(*) FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
        WHERE n.nspname = 'public' AND p.proname IN ('platform_reject_mutation', 'subscription_package_version_guard', 'tenant_primary_owner_guard',
                                                       'tenant_subscription_guard', 'user_invitation_guard')) AS existing_named_functions,
       (SELECT count(*) FROM pg_prepared_xacts)                                                        AS prepared_transactions,
       (SELECT count(*) FROM pg_stat_activity WHERE datname = current_database() AND pid <> pg_backend_pid()
          AND xact_start < now() - interval '5 minutes')                                               AS transactions_older_than_5_min,
       (SELECT count(*) FROM pg_stat_activity WHERE datname = current_database() AND pid <> pg_backend_pid()
          AND state LIKE 'idle in transaction%')                                                       AS idle_in_transaction,
       (SELECT count(*) FROM pg_locks l JOIN pg_class c ON c.oid = l.relation
        WHERE l.pid <> pg_backend_pid() AND c.relname IN ('orgs', 'users', 'sessions', 'platform_admins')) AS other_sessions_locks_on_key_tables;
SELECT has_database_privilege(current_user, current_database(), 'CREATE')                         AS role_can_create_schema,
