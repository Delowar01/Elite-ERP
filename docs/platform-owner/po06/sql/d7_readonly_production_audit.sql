-- =============================================================================================
-- PO-06 — D-7 READ-ONLY production measurement bundle (one file; consolidates and extends
-- po00/sql/02_readonly_baseline_queries.sql, po02d0/sql/02_legacy_onboarding_audit_readonly.sql and
-- po02d3/sql/users_email_audit_readonly.sql, which stay unchanged).
--
-- NOT EXECUTED AGAINST PRODUCTION. Validated only on loopback, disposable *_test_only_* databases
-- with fictional data (verify/verify-po06-rehearsal.mts, section D7). Running it against production —
-- or against a Neon branch of production — needs the owner's separate written approval and follows
-- docs/platform-owner/po06/D7_AUDIT_PROCEDURE.md (target, operator, window, file SHA-256, output location).
--
-- SAFETY, enforced by the server and by this file:
--   * ONE transaction: BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY … ROLLBACK (a consistent snapshot). The file
--     proves transaction_read_only = on and REPEATABLE READ before the first measurement and quits otherwise. Under
--     psql -1 PostgreSQL still applies this BEGIN's READ ONLY and REPEATABLE READ to the enclosing transaction (and
--     warns); inside a transaction that has already run a query, the isolation level cannot be set and the file stops
--     with an error before measuring anything;
--   * statement_timeout 15 s, lock_timeout 2 s, idle_in_transaction_session_timeout 60 s (SET LOCAL);
--   * plain SELECTs only: no INSERT / UPDATE / DELETE / MERGE / COPY / CREATE / ALTER / DROP / LOCK / DO /
--     CALL / FOR UPDATE / FOR SHARE, no temporary table, no function and no prepared statement is created;
--     every relation is read under ACCESS SHARE, so no application read, write or row lock is ever blocked;
--   * output is aggregates, catalog metadata and per-run pseudonyms only: no e-mail address, name, phone,
--     password hash, MFA secret, recovery code, token, invitation text, amount or other business content.
--     A pseudonym is the first 10 hex characters of sha256(per-run random salt || kind || id); the salt is
--     generated by the server, never printed and lost when psql exits, so a pseudonym links rows WITHIN
--     one report and cannot be turned back into an id;
--   * objects that may not exist yet (every Platform Owner object before D-6) are probed with to_regclass
--     and skipped with a note — the file never fails on their absence.
--
--   psql -X -q -v ON_ERROR_STOP=1 -f d7_readonly_production_audit.sql > <owner-controlled location>
-- (never -1, never -e / -a: echoing would print the salt). Exit status 0 = complete report; any other
-- status = the report is incomplete and nothing was changed (a timeout ends the transaction).
-- =============================================================================================
\set ON_ERROR_STOP on
BEGIN TRANSACTION ISOLATION LEVEL REPEATABLE READ READ ONLY;
SET LOCAL statement_timeout = '15s';
SET LOCAL lock_timeout = '2s';
SET LOCAL idle_in_transaction_session_timeout = '60s';

SELECT current_setting('transaction_read_only') = 'on'                  AS read_only,
       current_setting('transaction_isolation') = 'repeatable read'     AS snapshot,
       gen_random_uuid()::text                                          AS d7_salt,
       to_regclass('public.platform_admins') IS NOT NULL                AS has_platform,
       to_regclass('public.tenant_access_controls') IS NOT NULL         AS has_tac,
       to_regclass('public.organization_invitations') IS NOT NULL       AS has_inv,
       to_regclass('public.tenant_primary_owners') IS NOT NULL          AS has_tpo,
       to_regclass('public.tenant_subscriptions') IS NOT NULL           AS has_subs,
       to_regclass('public.subscription_package_versions') IS NOT NULL  AS has_versions,
       to_regclass('public.user_invitations') IS NOT NULL               AS has_uinv,
       to_regclass('drizzle.__drizzle_migrations') IS NOT NULL          AS has_journal \gset
\if :read_only
\else
  \echo 'REFUSED: the transaction is not read-only (run with psql -f only: never -1, never inside BEGIN)'
  \quit
\endif
\if :snapshot
\else
  \echo 'REFUSED: the transaction is not REPEATABLE READ'
  \quit
\endif

\echo '=== D7-00 environment and the measuring session (read-only proof)'
SELECT current_setting('server_version_num')                        AS server_version_num,
       current_setting('server_encoding')                           AS server_encoding,
       (SELECT datcollate FROM pg_database WHERE datname = current_database()) AS db_collate,
       (SELECT datctype   FROM pg_database WHERE datname = current_database()) AS db_ctype,
       pg_is_in_recovery()                                           AS standby,
       current_schema()                                              AS current_schema,
       current_setting('transaction_read_only')                      AS transaction_read_only,
       current_setting('default_transaction_read_only')              AS session_default_read_only,
       (SELECT rolsuper FROM pg_roles WHERE rolname = current_user)  AS measuring_role_is_superuser,
       current_setting('max_connections')                            AS max_connections,
       current_setting('max_locks_per_transaction')                  AS max_locks_per_transaction;

\echo '=== D7-01 companies'
SELECT count(*) AS companies,
       count(*) FILTER (WHERE created_at >= now() - interval '30 days') AS created_last_30_days
FROM orgs;

\echo '=== D7-02 legacy owner classification (PO-00 classes A–F; counts, then up to 20 pseudonyms per class)'
WITH o AS (
  SELECT g.id AS org_id,
         count(u.id)                                                     AS users,
         count(u.id) FILTER (WHERE u.role = 'owner' AND u.is_active)     AS active_owners,
         count(u.id) FILTER (WHERE u.role = 'owner' AND NOT u.is_active) AS inactive_owners
  FROM orgs g LEFT JOIN users u ON u.org_id = g.id
  GROUP BY g.id
), c AS (
  SELECT org_id,
         CASE
           WHEN users = 0                                 THEN 'E_no_users'
           WHEN active_owners = 1 AND inactive_owners = 0 THEN 'A_single_active_owner'
           WHEN active_owners = 1 AND inactive_owners > 0 THEN 'B_single_active_plus_inactive_owner'
           WHEN active_owners > 1                         THEN 'C_multiple_active_owners'
           WHEN active_owners = 0 AND inactive_owners > 0 THEN 'D_only_inactive_owner'
           ELSE                                                'F_no_owner_role'
         END AS class
  FROM o
)
SELECT class,
       count(*) AS companies,
       (array_agg('org-' || left(encode(sha256(convert_to(:'d7_salt' || ':org:' || org_id::text, 'UTF8')), 'hex'), 10) ORDER BY org_id))[1:20] AS pseudonyms
FROM c GROUP BY class ORDER BY class;

\echo '=== D7-03 users: active / disabled / never signed in / MFA (counts only)'
SELECT count(*)                                        AS users,
       count(*) FILTER (WHERE is_active)               AS active_users,
       count(*) FILTER (WHERE NOT is_active)           AS disabled_users,
       count(*) FILTER (WHERE last_login_at IS NULL)   AS never_signed_in,
       count(*) FILTER (WHERE mfa_enabled)             AS mfa_enabled_users,
       count(*) FILTER (WHERE mfa_enabled AND role = 'owner' AND is_active) AS mfa_enabled_active_owners
FROM users;

\echo '=== D7-04 owner roles and role values (users.role is free text; non-canonical values are never treated as owner)'
SELECT role, count(*) AS users,
       count(*) FILTER (WHERE is_active)     AS active,
       count(*) FILTER (WHERE NOT is_active) AS disabled,
       (role NOT IN ('owner', 'admin', 'staff')) AS non_canonical
FROM users GROUP BY role ORDER BY role;
SELECT count(*) FILTER (WHERE n_active_owner = 0) AS companies_without_an_active_owner,
       count(*) FILTER (WHERE n_owner > 0 AND n_active_owner = 0) AS companies_whose_only_owners_are_disabled
FROM (SELECT g.id,
             count(u.id) FILTER (WHERE u.role = 'owner')                 AS n_owner,
             count(u.id) FILTER (WHERE u.role = 'owner' AND u.is_active) AS n_active_owner
      FROM orgs g LEFT JOIN users u ON u.org_id = g.id GROUP BY g.id) s;

\echo '=== D7-05 companies without a primary owner mapping'
\if :has_tpo
SELECT count(*) AS companies,
