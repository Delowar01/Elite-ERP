\echo '=== D7-07 user seats per company (active + disabled users; the Trial seat count is 3)'
SELECT count(*) AS companies,
       coalesce(max(n), 0) AS max_users,
       percentile_disc(0.5)  WITHIN GROUP (ORDER BY n) AS p50_users,
       percentile_disc(0.95) WITHIN GROUP (ORDER BY n) AS p95_users,
       percentile_disc(0.99) WITHIN GROUP (ORDER BY n) AS p99_users,
       count(*) FILTER (WHERE n > 3) AS companies_above_3_users,
       count(*) FILTER (WHERE a > 3) AS companies_above_3_active_users
FROM (SELECT g.id, count(u.id) AS n, count(u.id) FILTER (WHERE u.is_active) AS a
      FROM orgs g LEFT JOIN users u ON u.org_id = g.id GROUP BY g.id) s;
SELECT CASE WHEN n = 0 THEN '0' WHEN n = 1 THEN '1' WHEN n = 2 THEN '2' WHEN n = 3 THEN '3'
            WHEN n <= 5 THEN '4-5' WHEN n <= 10 THEN '6-10' ELSE '11+' END AS users_per_company,
       count(*) AS companies
FROM (SELECT g.id, count(u.id) AS n FROM orgs g LEFT JOIN users u ON u.org_id = g.id GROUP BY g.id) s
GROUP BY 1 ORDER BY min(n);

\echo '=== D7-08 e-mail uniqueness (E1 must be 0 before users_email_lower_uq; counts and pseudonyms only)'
SELECT 'E1' AS check_id, count(*) AS case_insensitive_duplicate_groups, coalesce(max(n), 0) AS largest_group, coalesce(sum(n), 0) AS accounts_involved,
       count(*) FILTER (WHERE orgs > 1) AS groups_spanning_companies
FROM (SELECT count(*) AS n, count(DISTINCT org_id) AS orgs FROM users GROUP BY lower(email) HAVING count(*) > 1) d;
SELECT 'E1-groups' AS check_id,
       (array_agg(grp ORDER BY first_id))[1:50] AS pseudonymous_groups
FROM (SELECT min(id) AS first_id,
             array_agg('user-' || left(encode(sha256(convert_to(:'d7_salt' || ':user:' || id::text, 'UTF8')), 'hex'), 10) ORDER BY id)::text AS grp
      FROM users GROUP BY lower(email) HAVING count(*) > 1) g;
SELECT 'E2-E4' AS check_id,
       count(*) FILTER (WHERE email <> lower(btrim(email))) AS not_stored_normalized,
       count(*) FILTER (WHERE email <> btrim(email))        AS surrounding_white_space,
       count(*) FILTER (WHERE email ~ '[^\x01-\x7e]')        AS non_ascii,
       count(*) FILTER (WHERE email !~ '^[^@\s]+@[^@\s]+$') AS not_one_at_sign
FROM users;
\if :has_inv
SELECT 'E5' AS check_id, count(*) AS open_company_invitations_whose_owner_email_is_a_user
