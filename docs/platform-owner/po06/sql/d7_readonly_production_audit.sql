\endif
SELECT 'E6' AS check_id,
       (SELECT c.reltuples::bigint FROM pg_class c WHERE c.oid = 'public.users'::regclass) AS users_estimated_rows,
       pg_relation_size('public.users')       AS users_heap_bytes,
       pg_total_relation_size('public.users') AS users_total_bytes,
       (SELECT coalesce(col.collname, 'database default') FROM pg_attribute a LEFT JOIN pg_collation col ON col.oid = a.attcollation AND col.collname <> 'default'
        WHERE a.attrelid = 'public.users'::regclass AND a.attname = 'email') AS email_collation;
SELECT 'E7' AS check_id, conname, pg_get_constraintdef(oid) AS definition
FROM pg_constraint WHERE conrelid = 'public.users'::regclass AND contype = 'u' ORDER BY conname;
SELECT 'E8' AS check_id, count(*) AS existing_users_email_lower_uq FROM pg_class WHERE relname = 'users_email_lower_uq';

\echo '=== D7-09 schema and index compatibility with the D-6 manifest'
SELECT c.relname AS planned_object,
       (SELECT count(*) FROM pg_class x JOIN pg_namespace n ON n.oid = x.relnamespace WHERE n.nspname = 'public' AND x.relname = c.relname) AS exists_in_public
FROM (VALUES ('platform_admins'), ('platform_sessions'), ('platform_login_attempts'), ('platform_audit_events'),
             ('tenant_access_controls'), ('organization_invitations'), ('platform_settings'), ('subscription_packages'),
             ('subscription_package_versions'), ('tenant_primary_owners'), ('tenant_subscriptions'), ('subscription_events'),
             ('organization_invitation_terms'), ('user_invitations'), ('sessions_org_active_idx'), ('platform_audit_events_entity_idx'),
             ('users_org_id_id_uq'), ('users_email_lower_uq')) AS c(relname)
ORDER BY 1;
SELECT i.relname AS index_name, x.indisvalid AND x.indisready AS valid, pg_get_indexdef(x.indexrelid) AS definition
FROM pg_index x JOIN pg_class i ON i.oid = x.indexrelid JOIN pg_namespace n ON n.oid = i.relnamespace
WHERE n.nspname = 'public' AND i.relname IN ('sessions_org_active_idx', 'users_org_id_id_uq', 'users_email_lower_uq')
ORDER BY 1;
SELECT count(*) AS invalid_indexes_in_public,
       coalesce(array_agg(i.relname ORDER BY i.relname), '{}') AS names
FROM pg_index x JOIN pg_class i ON i.oid = x.indexrelid JOIN pg_namespace n ON n.oid = i.relnamespace
WHERE n.nspname = 'public' AND NOT (x.indisvalid AND x.indisready);
SELECT conname AS long_named_customer_fk, convalidated AS validated
FROM pg_constraint
WHERE contype = 'f' AND conname IN ('advance_application_releases_allocation_id_advance_applications',
                                    'delivery_challan_items_delivery_challan_id_delivery_challans_id',
                                    'proforma_invoice_items_proforma_invoice_id_proforma_invoices_id',
                                    'sales_invoices_payment_term_preset_id_payment_term_presets_id_f')
ORDER BY 1;
SELECT (SELECT count(*) FROM advance_application_releases r WHERE r.allocation_id IS NOT NULL
          AND NOT EXISTS (SELECT 1 FROM advance_applications a WHERE a.id = r.allocation_id))  AS orphans_advance_application_releases,
       (SELECT count(*) FROM delivery_challan_items r WHERE r.delivery_challan_id IS NOT NULL
          AND NOT EXISTS (SELECT 1 FROM delivery_challans a WHERE a.id = r.delivery_challan_id)) AS orphans_delivery_challan_items,
       (SELECT count(*) FROM proforma_invoice_items r WHERE r.proforma_invoice_id IS NOT NULL
          AND NOT EXISTS (SELECT 1 FROM proforma_invoices a WHERE a.id = r.proforma_invoice_id)) AS orphans_proforma_invoice_items,
       (SELECT count(*) FROM sales_invoices r WHERE r.payment_term_preset_id IS NOT NULL
          AND NOT EXISTS (SELECT 1 FROM payment_term_presets a WHERE a.id = r.payment_term_preset_id)) AS orphans_sales_invoices_payment_term;
SELECT t.tgname AS immutable_audit_trigger, c.relname AS on_table, t.tgenabled AS enabled
FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
WHERE t.tgname IN ('audit_logs_immutable', 'security_events_immutable') AND NOT t.tgisinternal
ORDER BY 1;
SELECT (SELECT count(*) FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public' AND NOT t.tgisinternal AND t.tgenabled <> 'O') AS disabled_triggers_in_public,
       (SELECT count(*) FROM pg_event_trigger)                                     AS event_triggers,
       (SELECT count(*) FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public' AND c.relkind = 'r' AND c.relrowsecurity)       AS tables_with_row_level_security,
       (SELECT count(*) FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p'))                    AS tables_in_public,
       (SELECT coalesce(array_agg(extname ORDER BY extname), '{}') FROM pg_extension) AS extensions;
\if :has_journal
SELECT count(*) AS drizzle_journal_rows, max(created_at) AS latest_created_at FROM drizzle.__drizzle_migrations;
