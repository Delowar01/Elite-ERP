\echo '=== D7-10 sizing (bytes; the database, the tables the migration touches, and the business tables)'
SELECT pg_database_size(current_database()) AS database_bytes;
SELECT c.relname AS table_name, c.reltuples::bigint AS estimated_rows,
       pg_relation_size(c.oid) AS heap_bytes, pg_indexes_size(c.oid) AS index_bytes, pg_total_relation_size(c.oid) AS total_bytes,
       s.last_autoanalyze, s.last_analyze, s.n_dead_tup
FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace LEFT JOIN pg_stat_user_tables s ON s.relid = c.oid
WHERE n.nspname = 'public' AND c.relkind = 'r'
  AND c.relname IN ('orgs', 'users', 'sessions', 'audit_logs', 'security_events', 'activity_logs', 'platform_admins', 'platform_audit_events')
ORDER BY c.relname;
SELECT count(*) AS business_tables, sum(pg_total_relation_size(c.oid)) AS business_total_bytes, max(pg_total_relation_size(c.oid)) AS largest_table_bytes
FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = 'public' AND c.relkind = 'r';
SELECT 'users_pkey' AS proxy_for_users_org_id_id_uq, pg_relation_size(to_regclass('public.users_pkey')) AS bytes;
SELECT 'sessions_pkey' AS proxy_for_sessions_org_active_idx, pg_relation_size(to_regclass('public.sessions_pkey')) AS bytes;
